CREATE OR REPLACE PROCEDURE ict371_lab.return_equipment(p_loan_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
 v_equipment_id integer;
 v_quantity integer;
BEGIN
 SELECT equipment_id, quantity
 INTO v_equipment_id, v_quantity
 FROM ict371_lab.equipment_loan
 WHERE loan_id = p_loan_id AND status = 'ACTIVE'
 FOR UPDATE;
 IF NOT FOUND THEN
 RAISE NOTICE 'No active loan with ID %', p_loan_id;
 RETURN;
 END IF;
 UPDATE ict371_lab.equipment_loan
 SET status = 'RETURNED' WHERE loan_id = p_loan_id;
 UPDATE ict371_lab.equipment
 SET available_quantity = available_quantity + v_quantity
 WHERE equipment_id = v_equipment_id;
 RAISE NOTICE 'Loan % returned; % units restored',
 p_loan_id, v_quantity;
END;
$$;

