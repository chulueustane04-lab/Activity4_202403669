CREATE OR REPLACE PROCEDURE ict371_lab.issue_equipment(
 p_equipment_id integer,
 p_student_number text,
 p_quantity integer
)
LANGUAGE plpgsql
AS $$
DECLARE
 v_available integer;
 v_loan_id integer;
BEGIN
 IF p_quantity <= 0 THEN
 RAISE EXCEPTION 'Quantity must be positive'
 USING ERRCODE = '22023';

 CALL ict371_lab.issue_equipment(1, 'STU001', 2);
CALL ict371_lab.issue_equipment(2, 'STU002', 1);
CALL ict371_lab.issue_equipment(2, 'STU003', 10);
 END IF;
 SELECT available_quantity INTO v_available
 FROM ict371_lab.equipment
 WHERE equipment_id = p_equipment_id
 FOR UPDATE;
 IF NOT FOUND THEN
 RAISE NOTICE 'Equipment % does not exist', p_equipment_id;
 RETURN;
 ELSIF v_available < p_quantity THEN
 RAISE NOTICE 'Insufficient stock: only % available', v_available;
 RETURN;
 END IF;
 UPDATE ict371_lab.equipment
 SET available_quantity = available_quantity - p_quantity
 WHERE equipment_id = p_equipment_id;
 INSERT INTO ict371_lab.equipment_loan
 (equipment_id, student_number, quantity, status)
 VALUES (p_equipment_id, p_student_number, p_quantity, 'ACTIVE')
 RETURNING loan_id INTO v_loan_id;
 RAISE NOTICE 'Loan % created for student %',
 v_loan_id, p_student_number;
END;
$$;

