CREATE OR REPLACE PROCEDURE ict371_lab.show_low_stock()
LANGUAGE plpgsql
AS $$
DECLARE
 v_item record;
 c_low CURSOR FOR
 SELECT equipment_name, available_quantity
 FROM ict371_lab.equipment
 WHERE available_quantity <= 2
 ORDER BY equipment_id;
BEGIN
 OPEN c_low;
 LOOP
 FETCH c_low INTO v_item;
 EXIT WHEN NOT FOUND;
 RAISE NOTICE 'Low stock: % (% remaining)',
 v_item.equipment_name, v_item.available_quantity;
 END LOOP;
 CLOSE c_low;
END;
$$;

